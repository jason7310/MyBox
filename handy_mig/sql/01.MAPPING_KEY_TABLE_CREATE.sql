-- ====================================================================================================
-- [통합 MIG] 01. 키 매핑 테이블 생성 및 사전 준비
-- 대상 DBMS : Tibero 7 (TAC 2-node 호환)
-- 목적 : DOC_ID 와 APPRID 간의 초경량 매핑 인덱스를 구축하여,
--        무거운 2차 매핑 테이블 및 PL/SQL 루프 UPDATE 없이
--        단 1회의 INSERT로 ORGAPPRID까지 일괄 확정하기 위한 기반 테이블입니다.
-- ====================================================================================================

-- 1. 세션 파라미터 최적화 (Tibero 7 병렬 DDL/DML 활성화)
ALTER SESSION ENABLE PARALLEL DDL;
ALTER SESSION ENABLE PARALLEL DML;

-- 2. 초경량 키 매핑 테이블 생성 (DOC_ID <-> APPRID)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE INTRAWARE.MG_APPR_KEY CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE INTRAWARE.MG_APPR_KEY (
    DOC_ID          VARCHAR2(40)    NOT NULL,
    ORIGIN_DOC_ID   VARCHAR2(40),
    APPRID          VARCHAR2(20)    NOT NULL,
    DOC_TYPE        CHAR(1)         NOT NULL, -- 'A': 기안(APP), 'E': 수신(ENF)
    DRAFTDATE       DATE,
    APPROVALDATE    DATE,
    COMP_ID         VARCHAR2(20)
)
NOLOGGING
TABLESPACE HDATA_1;

COMMENT ON TABLE  INTRAWARE.MG_APPR_KEY IS 'MIG 초경량 결재 키 매핑 테이블';
COMMENT ON COLUMN INTRAWARE.MG_APPR_KEY.DOC_ID IS 'AS-IS 문서ID';
COMMENT ON COLUMN INTRAWARE.MG_APPR_KEY.ORIGIN_DOC_ID IS 'AS-IS 원문서ID';
COMMENT ON COLUMN INTRAWARE.MG_APPR_KEY.APPRID IS 'TO-BE 결재ID(HANDY_ID)';
COMMENT ON COLUMN INTRAWARE.MG_APPR_KEY.DOC_TYPE IS '문서구분(A:기안, E:수신)';

-- 3. 고속 조인을 위한 인덱스 생성
CREATE UNIQUE INDEX INTRAWARE.PK_MG_APPR_KEY ON INTRAWARE.MG_APPR_KEY (DOC_ID)
NOLOGGING
TABLESPACE HINDEX_1;

ALTER TABLE INTRAWARE.MG_APPR_KEY ADD CONSTRAINT PK_MG_APPR_KEY PRIMARY KEY (DOC_ID) USING INDEX INTRAWARE.PK_MG_APPR_KEY;

CREATE INDEX INTRAWARE.IX_MAPPING_APPR_ORIGIN ON INTRAWARE.MG_APPR_KEY (ORIGIN_DOC_ID)
NOLOGGING
TABLESPACE HINDEX_1;

CREATE INDEX INTRAWARE.IX_MAPPING_APPR_APPRID ON INTRAWARE.MG_APPR_KEY (APPRID)
NOLOGGING
TABLESPACE HINDEX_1;