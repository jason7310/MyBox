-- 스크립트명 : 02.MG_POST_EXTRACT.sql
-- 작성목적   : 원천(BBS_USER.TBBS_POST_COMMON) 게시물 본문(CLOB) 및 메타데이터를 스테이징(MIG1_USER.MG_POST)으로 추출
-- 대상스키마 : 원천(BBS_USER.TBBS_POST_COMMON) -> 스테이징(MIG1_USER.MG_POST)
-- 정합성보장 :
--   1. 삭제 게시물(POST_TYPE = 'D') 및 임시저장(POST_TYPE = 'T') 제외, 정상 게시물 추출
--   2. 핸디 10.x INTRAWARE.BHEADER 규격에 맞춘 9자리 게시물 ID(HANDY_HEADER_ID: 'H' || 8자리 숫자) 자동 채번
--   3. 계층형 답글(TOP_POST_ID, PARENT_POST_ID, POST_DEPTH)에 대한 THREAD_ID / THREAD_SEQ / ORIG_ID 계산
--   4. CLOB 본문(CONTENT)을 보존하고 핸디 본문 파일 생성 경로(HANDY_BODY_PATH) 및 웹진 요약(BODY_TEXT) 자동 생성
-- ====================================================================================================

ALTER SESSION ENABLE PARALLEL DDL;
ALTER SESSION ENABLE PARALLEL DML;

-- 1. 게시물 스테이징 테이블 생성 (MIG1_USER.MG_POST)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE MIG1_USER.MG_POST CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE MIG1_USER.MG_POST (
    BOARD_ID            VARCHAR2(32)  NOT NULL, -- 원천 게시판 ID
    POST_ID             VARCHAR2(32)  NOT NULL, -- 원천 게시물 ID
    HANDY_BOARD_ID      CHAR(9)       NOT NULL, -- 핸디 9자리 게시판 ID (BBOARD.BRD_ID)
    HANDY_HEADER_ID     CHAR(9)       NOT NULL, -- 핸디 9자리 게시물 ID (BHEADER.HEADER_ID)
    MTRL_NO             NUMBER(9,0)   NOT NULL, -- 게시판 내 일련번호
    POST_TITLE          VARCHAR2(400) NOT NULL, -- 게시물 제목 (개행 정제 및 400B 방어)
    CONTENT             CLOB,                   -- 원천 게시물 본문 (HTML CLOB)
    BODY_TEXT           VARCHAR2(600),          -- 본문 태그 제거 요약 텍스트 (600B)
    HANDY_BODY_PATH     VARCHAR2(200) NOT NULL, -- 핸디 물리 본문파일 상대경로
    EDITORTYPE          VARCHAR2(1),            -- 원천 에디터 타입
    IS_EMERGENCY        CHAR(1) DEFAULT '0',    -- 긴급 여부 (EXPR_F)
    IS_SECURITY         CHAR(1) DEFAULT '0',    -- 보안 여부 (SEC_F)
    IS_SECRET_POST      CHAR(1) DEFAULT '0',    -- 비밀글 여부 (PRIVATE_F)
    IS_NOTICE           CHAR(1) DEFAULT '0',    -- 공지글 여부 (ANN_F)
    IS_FILE_POST        CHAR(1) DEFAULT '0',    -- 파일게시 여부
    ATTACH_ID           VARCHAR2(50),           -- 일반 첨부파일 묶음 ID (COM_USER.TCOM_FILE_ATTACH.FILE_FID)
    FILE_POST_ATTACH_ID VARCHAR2(50),           -- 파일게시 첨부 ID
    IMAGE_ATTACH_ID     VARCHAR2(255),          -- 본문 이미지 첨부 ID
    TOP_POST_ID         VARCHAR2(32),           -- 원천 최상위 게시물 ID
    PARENT_POST_ID      VARCHAR2(32),           -- 원천 부모 게시물 ID
    POST_DEPTH          NUMBER(2,0) DEFAULT 0,  -- 답글 깊이 (THREAD_DEPTH)
    HANDY_ORIG_ID       CHAR(9) DEFAULT '000000000', -- 핸디 원본(부모) 게시물 ID
    HANDY_THREAD_ID     NUMBER(14,0),           -- 핸디 쓰레드 번호
    HANDY_THREAD_SEQ    NUMBER(3,0) DEFAULT 0,  -- 핸디 쓰레드 내 순번
    POST_TYPE           VARCHAR2(1),            -- 원천 저장형태 (N:정상, C:심의, B:반려, T:임시, D:삭제)
    VIEW_COUNT          NUMBER(10,0) DEFAULT 0, -- 조회수 (READ_NUM)
    RCMD_COUNT          NUMBER(7,0)  DEFAULT 0, -- 추천/찬성수 (APPROVAL_NUM)
    NO_COUNT            NUMBER(7,0)  DEFAULT 0, -- 반대수 (OPPOSITE_NUM)
    COMMENT_COUNT       NUMBER(4,0)  DEFAULT 0, -- 덧글수 (COMMENT_NUM)
    ATT_CNT             NUMBER(3,0)  DEFAULT 0, -- 첨부파일 개수 (04번 스크립트에서 최종 보정)
    CREATOR_UID         VARCHAR2(32),           -- 원천 작성자 UID
    CREATOR_NAME        VARCHAR2(240),          -- 작성자명 (POSTER_NAME)
    CREATOR_DEPT_ID     VARCHAR2(45),           -- 원천 작성부서 ID
    CREATOR_DEPT_NAME   VARCHAR2(400),          -- 원천 작성부서명 (ORIG_DEPT_NAME)
    CREATE_DATE         DATE NOT NULL,          -- 등록일시 (POST_DATE)
    UPDATE_DATE         DATE NOT NULL,          -- 수정일시 (MODIFY_DATE)
    END_DATE            DATE NOT NULL,          -- 게시종료일시 (END_DATE)
    MIG_FILE_YN         CHAR(1) DEFAULT 'N',    -- 본문 CLOB 파일 추출 완료 여부
    CONSTRAINT PK_MG_POST PRIMARY KEY (BOARD_ID, POST_ID)
)
NOLOGGING;

CREATE UNIQUE INDEX MIG1_USER.UX_MG_POST_HEADER_ID ON MIG1_USER.MG_POST (HANDY_HEADER_ID) NOLOGGING;
CREATE INDEX MIG1_USER.IX_MG_POST_POST_ID          ON MIG1_USER.MG_POST (POST_ID) NOLOGGING;
CREATE INDEX MIG1_USER.IX_MG_POST_ATTACH_ID        ON MIG1_USER.MG_POST (ATTACH_ID) NOLOGGING;

COMMENT ON TABLE  MIG1_USER.MG_POST                 IS '게시물 본문 및 메타 이관 스테이징 테이블';
COMMENT ON COLUMN MIG1_USER.MG_POST.HANDY_HEADER_ID IS '핸디 10.x INTRAWARE.BHEADER.HEADER_ID (H00000001~)';
COMMENT ON COLUMN MIG1_USER.MG_POST.HANDY_BODY_PATH IS '핸디 BHEADER.BODY_PATH 물리 본문파일 경로';


-- 2. 원천 게시물 추출 및 1차 적재 (CLOB 포함하므로 병렬 DML 대신 Direct Path 처리)
INSERT /*+ APPEND */ INTO MIG1_USER.MG_POST (
    BOARD_ID,
    POST_ID,
    HANDY_BOARD_ID,
    HANDY_HEADER_ID,
    MTRL_NO,
    POST_TITLE,
    CONTENT,
    BODY_TEXT,
    HANDY_BODY_PATH,
    EDITORTYPE,
    IS_EMERGENCY,
    IS_SECURITY,
    IS_SECRET_POST,
    IS_NOTICE,
    IS_FILE_POST,
    ATTACH_ID,
    FILE_POST_ATTACH_ID,
    IMAGE_ATTACH_ID,
    TOP_POST_ID,
    PARENT_POST_ID,
    POST_DEPTH,
    HANDY_ORIG_ID,
    HANDY_THREAD_ID,
    HANDY_THREAD_SEQ,
    POST_TYPE,
    VIEW_COUNT,
    RCMD_COUNT,
    NO_COUNT,
    COMMENT_COUNT,
    ATT_CNT,
    CREATOR_UID,
    CREATOR_NAME,
    CREATOR_DEPT_ID,
    CREATOR_DEPT_NAME,
    CREATE_DATE,
    UPDATE_DATE,
    END_DATE,
    MIG_FILE_YN
)
SELECT
    P.BOARD_ID,
    P.POST_ID,
    B.HANDY_BOARD_ID,
    'H' || LPAD(P.GLOBAL_SEQ, 8, '0') AS HANDY_HEADER_ID,
    P.MTRL_NO,
    NVL(
        SUBSTRB(
            TRIM(REPLACE(REPLACE(P.POST_TITLE, CHR(13), ' '), CHR(10), ' ')),
            1, 400
        ),
        '(제목없음)'
    ) AS POST_TITLE,
    P.CONTENT,
    SUBSTRB(
        TRIM(REGEXP_REPLACE(DBMS_LOB.SUBSTR(P.CONTENT, 1000, 1), '<[^>]+>|&nbsp;|' || CHR(13) || '|' || CHR(10), ' ')),
        1, 600
    ) AS BODY_TEXT,
    '/bbs/' || TO_CHAR(P.CLEAN_CREATE_DATE, 'YYYY/MM/') || B.HANDY_BOARD_ID || '/H' || LPAD(P.GLOBAL_SEQ, 8, '0') || '.html' AS HANDY_BODY_PATH,
    P.EDITORTYPE,
    CASE WHEN P.IS_EMERGENCY IN ('1', 'Y') THEN '1' ELSE '0' END AS IS_EMERGENCY,
    CASE WHEN P.IS_SECURITY  IN ('1', 'Y') THEN '1' ELSE '0' END AS IS_SECURITY,
    CASE WHEN P.IS_SECRET_POST IN ('1', 'Y') THEN '1' ELSE '0' END AS IS_SECRET_POST,
    CASE WHEN P.IS_NOTICE    IN ('1', 'Y') THEN '1' ELSE '0' END AS IS_NOTICE,
    CASE WHEN P.IS_FILE_POST IN ('1', 'Y') THEN '1' ELSE '0' END AS IS_FILE_POST,
    TRIM(P.ATTACH_ID) AS ATTACH_ID,
    TRIM(P.FILE_POST_ATTACH_ID) AS FILE_POST_ATTACH_ID,
    TRIM(P.IMAGE_ATTACH_ID) AS IMAGE_ATTACH_ID,
    TRIM(P.TOP_POST_ID) AS TOP_POST_ID,
    TRIM(P.PARENT_POST_ID) AS PARENT_POST_ID,
    LEAST(NVL(P.POST_DEPTH, 0), 99) AS POST_DEPTH,
    '000000000' AS HANDY_ORIG_ID,
    P.GLOBAL_SEQ AS HANDY_THREAD_ID,
    P.THREAD_SEQ AS HANDY_THREAD_SEQ,
    NVL(P.POST_TYPE, 'N') AS POST_TYPE,
    NVL(P.VIEW_COUNT, 0) AS VIEW_COUNT,
    NVL(P.RCMD_COUNT, 0) + NVL(P.YES_COUNT, 0) AS RCMD_COUNT,
    NVL(P.NO_COUNT, 0) AS NO_COUNT,
    LEAST(NVL(P.COMMENT_COUNT, 0), 9999) AS COMMENT_COUNT,
    0 AS ATT_CNT,
    TRIM(P.CREATOR_UID) AS CREATOR_UID,
    NVL(SUBSTRB(TRIM(NVL(P.CREATOR_NAME, P.REGISTER)), 1, 240), '관리자') AS CREATOR_NAME,
    TRIM(P.CREATOR_DEPT_ID) AS CREATOR_DEPT_ID,
    SUBSTRB(TRIM(P.CREATOR_DEPT_NAME), 1, 400) AS CREATOR_DEPT_NAME,
    P.CLEAN_CREATE_DATE AS CREATE_DATE,
    P.CLEAN_UPDATE_DATE AS UPDATE_DATE,
    CASE
        WHEN REGEXP_LIKE(TRIM(P.POST_LIFECYCLE_ENDDATE), '^[0-9]{8}$')
             AND TRIM(P.POST_LIFECYCLE_ENDDATE) <= '29991231'
        THEN TO_DATE(TRIM(P.POST_LIFECYCLE_ENDDATE), 'YYYYMMDD')
        ELSE TO_DATE('30000101', 'YYYYMMDD')
    END AS END_DATE,
    'N' AS MIG_FILE_YN
FROM (
    SELECT
        PC.*,
        COALESCE(CAST(PC.CREATE_DATE AS DATE), SYSDATE) AS CLEAN_CREATE_DATE,
        COALESCE(CAST(PC.UPDATE_DATE AS DATE), CAST(PC.CREATE_DATE AS DATE), SYSDATE) AS CLEAN_UPDATE_DATE,
        ROW_NUMBER() OVER (
            ORDER BY COALESCE(CAST(PC.CREATE_DATE AS DATE), SYSDATE) ASC, PC.BOARD_ID ASC, PC.POST_ID ASC
        ) AS GLOBAL_SEQ,
        ROW_NUMBER() OVER (
            PARTITION BY PC.BOARD_ID
            ORDER BY COALESCE(CAST(PC.CREATE_DATE AS DATE), SYSDATE) ASC, PC.POST_ID ASC
        ) AS MTRL_NO,
        ROW_NUMBER() OVER (
            PARTITION BY PC.BOARD_ID, NVL(PC.TOP_POST_ID, PC.POST_ID)
            ORDER BY COALESCE(CAST(PC.CREATE_DATE AS DATE), SYSDATE) ASC, PC.POST_ID ASC
        ) - 1 AS THREAD_SEQ
    FROM BBS_USER.TBBS_POST_COMMON PC
    WHERE NVL(PC.POST_TYPE, 'N') NOT IN ('D', 'T') -- 삭제('D') 및 임시저장('T') 제외
) P
JOIN MIG1_USER.MG_BOARD B
  ON P.BOARD_ID = B.BOARD_ID;

COMMIT;


-- 3. 계층형 답글(TOP_POST_ID / PARENT_POST_ID)의 HANDY_ORIG_ID 및 HANDY_THREAD_ID 보정
MERGE INTO MIG1_USER.MG_POST T
USING (
    SELECT
        C.ROWID AS RID,
        NVL(P_PAR.HANDY_HEADER_ID, NVL(P_TOP.HANDY_HEADER_ID, '000000000')) AS NEW_ORIG_ID,
        NVL(P_TOP.HANDY_THREAD_ID, C.HANDY_THREAD_ID) AS NEW_THREAD_ID
    FROM MIG1_USER.MG_POST C
    LEFT JOIN MIG1_USER.MG_POST P_PAR
      ON C.BOARD_ID = P_PAR.BOARD_ID
     AND C.PARENT_POST_ID = P_PAR.POST_ID
    LEFT JOIN MIG1_USER.MG_POST P_TOP
      ON C.BOARD_ID = P_TOP.BOARD_ID
     AND C.TOP_POST_ID = P_TOP.POST_ID
    WHERE C.PARENT_POST_ID IS NOT NULL
       OR (C.TOP_POST_ID IS NOT NULL AND C.TOP_POST_ID <> C.POST_ID)
) S
ON (T.ROWID = S.RID)
WHEN MATCHED THEN
UPDATE SET
    T.HANDY_ORIG_ID   = S.NEW_ORIG_ID,
    T.HANDY_THREAD_ID = S.NEW_THREAD_ID;

COMMIT;

-- 4. 적재 결과 검증
SELECT
    COUNT(*) AS TOTAL_POSTS,
    MIN(HANDY_HEADER_ID) AS MIN_HEADER_ID,
    MAX(HANDY_HEADER_ID) AS MAX_HEADER_ID,
    SUM(CASE WHEN ATTACH_ID IS NOT NULL OR FILE_POST_ATTACH_ID IS NOT NULL THEN 1 ELSE 0 END) AS POSTS_WITH_ATTACH_KEY
FROM MIG1_USER.MG_POST;

