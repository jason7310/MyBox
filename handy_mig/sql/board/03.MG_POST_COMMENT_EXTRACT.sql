-- 스크립트명 : 03.MG_POST_COMMENT_EXTRACT.sql
-- 작성목적   : 원천(BBS_USER.TBBS_POST_COMMENT) 게시물 덧글을 스테이징(MIG1_USER.MG_POST_COMMENT)으로 추출
-- 대상스키마 : 원천(BBS_USER.TBBS_POST_COMMENT) -> 스테이징(MIG1_USER.MG_POST_COMMENT)
-- 정합성보장 :
--   1. 이관 대상 게시물(MIG1_USER.MG_POST)과 매핑되는 덧글 전수 추출
--   2. 핸디 10.x INTRAWARE.BBS_COMMENT 규격 9자리 의견 ID(HANDY_COMMENT_ID: 'C' || 8자리 숫자) 자동 채번
--   3. 대댓글(PARENT_COMMENT_ID)에 대한 핸디 상위의견 ID(HANDY_PAR_ID) 매핑 및 MG_POST.COMMENT_COUNT 동기화
-- ====================================================================================================

ALTER SESSION ENABLE PARALLEL DDL;
ALTER SESSION ENABLE PARALLEL DML;

-- 1. 덧글 스테이징 테이블 생성 (MIG1_USER.MG_POST_COMMENT)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE MIG1_USER.MG_POST_COMMENT CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE MIG1_USER.MG_POST_COMMENT (
    BOARD_ID            VARCHAR2(32)   NOT NULL, -- 원천 게시판 ID
    POST_ID             VARCHAR2(32)   NOT NULL, -- 원천 게시물 ID
    COMMENT_ID          VARCHAR2(32)   NOT NULL, -- 원천 덧글 ID
    HANDY_COMMENT_ID    CHAR(9)        NOT NULL, -- 핸디 9자리 의견 ID (BBS_COMMENT.COMMENT_ID)
    HANDY_HEADER_ID     CHAR(9)        NOT NULL, -- 핸디 9자리 게시물 ID (BBS_COMMENT.HEADER_ID)
    HANDY_BOARD_ID      CHAR(9)        NOT NULL, -- 핸디 9자리 게시판 ID (BBS_COMMENT.BRD_ID)
    PARENT_COMMENT_ID   VARCHAR2(32),            -- 원천 부모 덧글 ID
    HANDY_PAR_ID        CHAR(9) DEFAULT '000000000', -- 핸디 상위 의견 ID (BBS_COMMENT.PAR_ID)
    COMMENT_ORDER       NUMBER(4,0) DEFAULT 1,   -- 덧글 순번
    COMMENT_CONTENT     VARCHAR2(4000),          -- 덧글 내용 (USER_COMMENT)
    CREATOR_UID         VARCHAR2(32),            -- 작성자 원천 UID
    CREATOR_NAME        VARCHAR2(120),           -- 작성자명 (ALIAS)
    CREATE_DATE         DATE NOT NULL,           -- 등록일시 (ORIG_COMMENT_DATE / M_COMMENT_DATE)
    CONSTRAINT PK_MG_POST_COMMENT PRIMARY KEY (BOARD_ID, POST_ID, COMMENT_ID)
)
NOLOGGING;

CREATE UNIQUE INDEX MIG1_USER.UX_MG_COMMENT_HANDY_ID ON MIG1_USER.MG_POST_COMMENT (HANDY_COMMENT_ID) NOLOGGING;
CREATE INDEX MIG1_USER.IX_MG_COMMENT_HEADER_ID       ON MIG1_USER.MG_POST_COMMENT (HANDY_HEADER_ID) NOLOGGING;

COMMENT ON TABLE  MIG1_USER.MG_POST_COMMENT                  IS '게시물 덧글(의견) 이관 스테이징 테이블';
COMMENT ON COLUMN MIG1_USER.MG_POST_COMMENT.HANDY_COMMENT_ID IS '핸디 10.x INTRAWARE.BBS_COMMENT.COMMENT_ID (C00000001~)';


-- 2. 원천 덧글 추출 및 적재
INSERT /*+ APPEND */ INTO MIG1_USER.MG_POST_COMMENT (
    BOARD_ID,
    POST_ID,
    COMMENT_ID,
    HANDY_COMMENT_ID,
    HANDY_HEADER_ID,
    HANDY_BOARD_ID,
    PARENT_COMMENT_ID,
    HANDY_PAR_ID,
    COMMENT_ORDER,
    COMMENT_CONTENT,
    CREATOR_UID,
    CREATOR_NAME,
    CREATE_DATE
)
SELECT
    C.BOARD_ID,
    C.POST_ID,
    C.COMMENT_ID,
    'C' || LPAD(
        ROW_NUMBER() OVER (
            ORDER BY COALESCE(CAST(C.CREATE_DATE AS DATE), P.CREATE_DATE, SYSDATE) ASC,
                     C.BOARD_ID ASC,
                     C.POST_ID ASC,
                     NVL(C.COMMENT_ORDER, 1) ASC,
                     C.COMMENT_ID ASC
        ), 8, '0'
    ) AS HANDY_COMMENT_ID,
    P.HANDY_HEADER_ID,
    P.HANDY_BOARD_ID,
    TRIM(C.PARENT_COMMENT_ID) AS PARENT_COMMENT_ID,
    '000000000' AS HANDY_PAR_ID,
    ROW_NUMBER() OVER (
        PARTITION BY C.BOARD_ID, C.POST_ID
        ORDER BY COALESCE(CAST(C.CREATE_DATE AS DATE), P.CREATE_DATE, SYSDATE) ASC,
                 NVL(C.COMMENT_ORDER, 1) ASC,
                 C.COMMENT_ID ASC
    ) AS COMMENT_ORDER,
    NVL(SUBSTRB(TRIM(C.COMMENT_CONTENT), 1, 4000), ' ') AS COMMENT_CONTENT,
    TRIM(C.CREATOR_UID) AS CREATOR_UID,
    SUBSTRB(TRIM(C.CREATOR_NAME), 1, 120) AS CREATOR_NAME,
    COALESCE(CAST(C.CREATE_DATE AS DATE), P.CREATE_DATE, SYSDATE) AS CREATE_DATE
FROM BBS_USER.TBBS_POST_COMMENT C
JOIN MIG1_USER.MG_POST P
  ON C.BOARD_ID = P.BOARD_ID
 AND C.POST_ID  = P.POST_ID;

COMMIT;


-- 3. 대댓글(PARENT_COMMENT_ID)의 HANDY_PAR_ID 매핑 보정
MERGE INTO MIG1_USER.MG_POST_COMMENT T
USING (
    SELECT
        C.ROWID AS RID,
        NVL(PAR.HANDY_COMMENT_ID, '000000000') AS NEW_PAR_ID
    FROM MIG1_USER.MG_POST_COMMENT C
    JOIN MIG1_USER.MG_POST_COMMENT PAR
      ON C.BOARD_ID = PAR.BOARD_ID
     AND C.POST_ID  = PAR.POST_ID
     AND C.PARENT_COMMENT_ID = PAR.COMMENT_ID
    WHERE C.PARENT_COMMENT_ID IS NOT NULL
      AND C.PARENT_COMMENT_ID <> C.COMMENT_ID
) S
ON (T.ROWID = S.RID)
WHEN MATCHED THEN
UPDATE SET T.HANDY_PAR_ID = S.NEW_PAR_ID;

COMMIT;


-- 4. 게시물 마스터(MG_POST)의 실제 덧글 건수(COMMENT_COUNT) 정합성 동기화
MERGE INTO MIG1_USER.MG_POST P
USING (
    SELECT
        HANDY_HEADER_ID,
        LEAST(COUNT(*), 9999) AS REAL_COMMENT_CNT
    FROM MIG1_USER.MG_POST_COMMENT
    GROUP BY HANDY_HEADER_ID
) C
ON (P.HANDY_HEADER_ID = C.HANDY_HEADER_ID)
WHEN MATCHED THEN
UPDATE SET P.COMMENT_COUNT = C.REAL_COMMENT_CNT;

COMMIT;

-- 5. 적재 결과 검증
SELECT
    COUNT(*) AS TOTAL_COMMENTS,
    COUNT(DISTINCT HANDY_HEADER_ID) AS POSTS_WITH_COMMENTS,
    MIN(HANDY_COMMENT_ID) AS MIN_COMMENT_ID,
    MAX(HANDY_COMMENT_ID) AS MAX_COMMENT_ID
FROM MIG1_USER.MG_POST_COMMENT;

