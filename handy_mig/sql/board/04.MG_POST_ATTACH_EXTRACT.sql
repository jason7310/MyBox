-- ====================================================================================================
-- 스크립트명 : 04.MG_POST_ATTACH_EXTRACT.sql
-- 작성목적   : 원천(COM_USER.TCOM_FILE_ATTACH / BBS_USER.TBBS_FILE_ATTACH_HIS) 게시물 첨부파일 추출
-- 대상스키마 : 원천(COM_USER, BBS_USER) -> 스테이징(MIG1_USER.MG_POST_ATTACH)
-- 정합성보장 :
--   1. MG_POST.ATTACH_ID 및 FILE_POST_ATTACH_ID와 원천 FILE_FID를 조인하여 누락 없이 추출
--   2. COM_USER.TCOM_FILE_ATTACH를 기본으로 조회하되, 누락 건은 BBS_USER.TBBS_FILE_ATTACH_HIS에서 보완
--   3. 핸디 10.x INTRAWARE.BBS_ATTACH 규격(HEADER_ID, ORD, TYPE, ATT_SIZE, FILE_NAME, ATT_URL) 매핑
--   4. 추출 완료 후 MG_POST.ATT_CNT(게시물별 실제 첨부파일 개수)를 1:1 동기화
-- ====================================================================================================

ALTER SESSION ENABLE PARALLEL DDL;
ALTER SESSION ENABLE PARALLEL DML;

-- 1. 첨부파일 스테이징 테이블 생성 (MIG1_USER.MG_POST_ATTACH)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE MIG1_USER.MG_POST_ATTACH CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE MIG1_USER.MG_POST_ATTACH (
    HANDY_HEADER_ID       CHAR(9)        NOT NULL, -- 핸디 9자리 게시물 ID (BBS_ATTACH.HEADER_ID)
    ORD                   NUMBER(3,0)    NOT NULL, -- 게시물 내 첨부 순번 (BBS_ATTACH.ORD: 1~)
    BOARD_ID              VARCHAR2(32)   NOT NULL, -- 원천 게시판 ID
    POST_ID               VARCHAR2(32)   NOT NULL, -- 원천 게시물 ID
    HANDY_BOARD_ID        CHAR(9)        NOT NULL, -- 핸디 9자리 게시판 ID
    FILE_FID              VARCHAR2(50)   NOT NULL, -- 원천 첨부파일 묶음 ID (ATTACH_ID)
    FILE_SEQ              NUMBER(10,0)   NOT NULL, -- 원천 파일 순번
    FILE_LOCAL_NAME       VARCHAR2(1000) NOT NULL, -- 원본 파일명 (BBS_ATTACH.FILE_NAME)
    FILE_SERVER_NAME      VARCHAR2(300),           -- 원천 서버 저장 파일명
    FILE_REAL_PATH        VARCHAR2(300),           -- 원천 실제 파일 디렉토리 경로
    FILE_REAL_SERVER_NAME VARCHAR2(300),           -- 원천 실제 서버 파일명
    FILE_SIZE             NUMBER(10,0) DEFAULT 0,  -- 파일 크기 Byte (BBS_ATTACH.ATT_SIZE)
    FILE_TYPE             VARCHAR2(150),           -- 파일 확장자/MIME 타입
    FILE_DATE             DATE,                    -- 파일 등록일시
    HANDY_ATT_URL         VARCHAR2(400)  NOT NULL, -- 핸디 타겟 첨부경로 (BBS_ATTACH.ATT_URL)
    MIG_COPY_YN           CHAR(1) DEFAULT 'N',     -- 물리 파일 복사 완료 여부
    CONSTRAINT PK_MG_POST_ATTACH PRIMARY KEY (HANDY_HEADER_ID, ORD)
)
NOLOGGING;

CREATE INDEX MIG1_USER.IX_MG_POST_ATTACH_POST ON MIG1_USER.MG_POST_ATTACH (BOARD_ID, POST_ID) NOLOGGING;
CREATE INDEX MIG1_USER.IX_MG_POST_ATTACH_FID  ON MIG1_USER.MG_POST_ATTACH (FILE_FID) NOLOGGING;

COMMENT ON TABLE  MIG1_USER.MG_POST_ATTACH               IS '게시물 첨부파일 이관 스테이징 테이블';
COMMENT ON COLUMN MIG1_USER.MG_POST_ATTACH.HANDY_ATT_URL IS '핸디 10.x INTRAWARE.BBS_ATTACH.ATT_URL 경로';


-- 2. 원천 첨부파일 추출 및 적재 (COM_USER.TCOM_FILE_ATTACH + TBBS_FILE_ATTACH_HIS 통합)
INSERT /*+ APPEND */ INTO MIG1_USER.MG_POST_ATTACH (
    HANDY_HEADER_ID,
    ORD,
    BOARD_ID,
    POST_ID,
    HANDY_BOARD_ID,
    FILE_FID,
    FILE_SEQ,
    FILE_LOCAL_NAME,
    FILE_SERVER_NAME,
    FILE_REAL_PATH,
    FILE_REAL_SERVER_NAME,
    FILE_SIZE,
    FILE_TYPE,
    FILE_DATE,
    HANDY_ATT_URL,
    MIG_COPY_YN
)
WITH RAW_FILES AS (
    -- 1순위: COM_USER.TCOM_FILE_ATTACH (공통 첨부파일 마스터)
    SELECT
        TRIM(F.FILE_FID) AS FILE_FID,
        NVL(F.FILE_SEQ, 1) AS FILE_SEQ,
        TRIM(F.FILE_LOCAL_NAME) AS FILE_LOCAL_NAME,
        TRIM(F.FILE_SERVER_NAME) AS FILE_SERVER_NAME,
        TRIM(NVL(F.FILE_REAL_PATH, F.EKP_FILE_PATH)) AS FILE_REAL_PATH,
        TRIM(NVL(F.FILE_REAL_SERVER_NAME, NVL(F.FILE_SERVER_NAME, F.EKP_FILE_NAME))) AS FILE_REAL_SERVER_NAME,
        NVL(F.FILE_SIZE, 0) AS FILE_SIZE,
        TRIM(F.FILE_TYPE) AS FILE_TYPE,
        CAST(F.FILE_DATE AS DATE) AS FILE_DATE,
        1 AS SRC_PRIORITY
    FROM COM_USER.TCOM_FILE_ATTACH F
    WHERE F.FILE_FID IS NOT NULL
    UNION ALL
    -- 2순위: BBS_USER.TBBS_FILE_ATTACH_HIS (TCOM_FILE_ATTACH에 없을 경우 대비)
    SELECT
        TRIM(H.FILE_FID) AS FILE_FID,
        NVL(H.FILE_SEQ, 1) AS FILE_SEQ,
        TRIM(H.FILE_LOCAL_NAME) AS FILE_LOCAL_NAME,
        TRIM(H.FILE_SERVER_NAME) AS FILE_SERVER_NAME,
        NULL AS FILE_REAL_PATH,
        TRIM(H.FILE_SERVER_NAME) AS FILE_REAL_SERVER_NAME,
        NVL(H.FILE_SIZE, 0) AS FILE_SIZE,
        TRIM(H.FILE_TYPE) AS FILE_TYPE,
        CAST(H.FILE_DATE AS DATE) AS FILE_DATE,
        2 AS SRC_PRIORITY
    FROM BBS_USER.TBBS_FILE_ATTACH_HIS H
    WHERE H.FILE_FID IS NOT NULL
),
DEDUP_FILES AS (
    SELECT
        FILE_FID,
        FILE_SEQ,
        FILE_LOCAL_NAME,
        FILE_SERVER_NAME,
        FILE_REAL_PATH,
        FILE_REAL_SERVER_NAME,
        FILE_SIZE,
        FILE_TYPE,
        FILE_DATE,
        ROW_NUMBER() OVER (
            PARTITION BY FILE_FID, FILE_SEQ
            ORDER BY SRC_PRIORITY ASC, FILE_DATE DESC NULLS LAST
        ) AS RN
    FROM RAW_FILES
),
POST_FID_MAP AS (
    -- 일반 첨부(ATTACH_ID)
    SELECT BOARD_ID, POST_ID, HANDY_BOARD_ID, HANDY_HEADER_ID, CREATE_DATE, ATTACH_ID AS TARGET_FID, 1 AS FID_TYPE
    FROM MIG1_USER.MG_POST
    WHERE ATTACH_ID IS NOT NULL
    UNION
    -- 파일게시 첨부(FILE_POST_ATTACH_ID)가 별도로 존재하는 경우
    SELECT BOARD_ID, POST_ID, HANDY_BOARD_ID, HANDY_HEADER_ID, CREATE_DATE, FILE_POST_ATTACH_ID AS TARGET_FID, 2 AS FID_TYPE
    FROM MIG1_USER.MG_POST
    WHERE FILE_POST_ATTACH_ID IS NOT NULL
      AND NVL(FILE_POST_ATTACH_ID, ' ') <> NVL(ATTACH_ID, ' ')
)
SELECT
    PM.HANDY_HEADER_ID,
    ROW_NUMBER() OVER (
        PARTITION BY PM.HANDY_HEADER_ID
        ORDER BY PM.FID_TYPE ASC, DF.FILE_SEQ ASC
    ) AS ORD,
    PM.BOARD_ID,
    PM.POST_ID,
    PM.HANDY_BOARD_ID,
    DF.FILE_FID,
    DF.FILE_SEQ,
    NVL(
        SUBSTRB(
            REPLACE(REPLACE(DF.FILE_LOCAL_NAME, CHR(13), ''), CHR(10), ''),
            1, 1000
        ),
        'attached_file_' || DF.FILE_SEQ
    ) AS FILE_LOCAL_NAME,
    DF.FILE_SERVER_NAME,
    DF.FILE_REAL_PATH,
    DF.FILE_REAL_SERVER_NAME,
    LEAST(NVL(DF.FILE_SIZE, 0), 2147483647) AS FILE_SIZE,
    DF.FILE_TYPE,
    COALESCE(DF.FILE_DATE, PM.CREATE_DATE, SYSDATE) AS FILE_DATE,
    '/bbs/' || TO_CHAR(PM.CREATE_DATE, 'YYYY/MM/') || PM.HANDY_BOARD_ID || '/' ||
        PM.HANDY_HEADER_ID || '_' ||
        ROW_NUMBER() OVER (
            PARTITION BY PM.HANDY_HEADER_ID
            ORDER BY PM.FID_TYPE ASC, DF.FILE_SEQ ASC
        ) AS HANDY_ATT_URL,
    'N' AS MIG_COPY_YN
FROM POST_FID_MAP PM
JOIN DEDUP_FILES DF
  ON PM.TARGET_FID = DF.FILE_FID
 AND DF.RN = 1;

COMMIT;


-- 3. 게시물 마스터(MG_POST)의 첨부파일 개수(ATT_CNT) 정합성 동기화
MERGE INTO MIG1_USER.MG_POST P
USING (
    SELECT
        HANDY_HEADER_ID,
        LEAST(COUNT(*), 999) AS REAL_ATT_CNT
    FROM MIG1_USER.MG_POST_ATTACH
    GROUP BY HANDY_HEADER_ID
) A
ON (P.HANDY_HEADER_ID = A.HANDY_HEADER_ID)
WHEN MATCHED THEN
UPDATE SET P.ATT_CNT = A.REAL_ATT_CNT;

COMMIT;

-- 4. 적재 결과 검증
SELECT
    COUNT(*) AS TOTAL_ATTACH_FILES,
    COUNT(DISTINCT HANDY_HEADER_ID) AS POSTS_WITH_ATTACH,
    ROUND(SUM(FILE_SIZE) / 1024 / 1024 / 1024, 2) AS TOTAL_SIZE_GB
FROM MIG1_USER.MG_POST_ATTACH;

