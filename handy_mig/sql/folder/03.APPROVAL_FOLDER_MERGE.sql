-- ============================================================================
-- [통합 MIG] 기록물철 후속 처리 - 03. 결재문서 편철 매핑 및 FOLDERID 업데이트
-- 
-- * 목적: rtool.sh로 등록된 편철함(APPRFOLDER)의 FLDRID를 결재문서(APPROVAL.FOLDERID)에
--         고속 MERGE 업데이트하고, 기록물철 문서 멤버(FLDRMBR2)를 동시 적재합니다.
-- ============================================================================

ALTER SESSION ENABLE PARALLEL DML;

-- 1. 대용량 조인 최적화를 위한 임시 인덱스 생성
CREATE INDEX INTRAWARE.IX_TMP_APPR_FOLDER ON INTRAWARE.APPROVAL (SAVEDEPTID, SPECIALLIST1, DRAFTDATE);
CREATE INDEX INTRAWARE.IX_TMP_APPRFLDR_MAP ON INTRAWARE.APPRFOLDER (PROCDEPTID, KEEPINGPERIODCAUSE, FLDRINFOYEAR);

-- 2. APPROVAL 테이블의 FOLDERID 일괄 MERGE 업데이트
MERGE /*+ PARALLEL(AP, 16) APPEND NOLOGGING */ INTO INTRAWARE.APPROVAL AP
USING (
    SELECT /*+ PARALLEL(16) ORDERED USE_NL(A AF) */
        AF.FLDRID,
        A.APPRID
    FROM INTRAWARE.APPROVAL A
    JOIN INTRAWARE.APPRFOLDER AF
      ON A.SPECIALLIST1 = AF.KEEPINGPERIODCAUSE
     AND A.SAVEDEPTID = AF.PROCDEPTID
     AND TO_CHAR(A.DRAFTDATE, 'YYYY') = AF.FLDRINFOYEAR
   WHERE A.FOLDERID IS NULL OR A.FOLDERID = '00000000000000000000'
) TMP
ON (AP.APPRID = TMP.APPRID)
WHEN MATCHED THEN
UPDATE SET AP.FOLDERID = TMP.FLDRID;

COMMIT;

-- 3. 기록물철 문서 멤버(FLDRMBR2) 적재
INSERT /*+ APPEND PARALLEL(FLDRMBR2, 16) */ INTO INTRAWARE.FLDRMBR2 (
    FLDRID,
    FLDRMBRID,
    INDEXDATE,
    REGISTDATE,
    REGISTERID,
    UPDATEDATE,
    UPDATERID
)
SELECT 
    AP.FOLDERID AS FLDRID,
    AP.APPRID AS FLDRMBRID,
    AP.INDEXDATE,
    NVL(AP.REGISTDATE, AP.DRAFTDATE) AS REGISTDATE,
    AP.DRAFTERID AS REGISTERID,
    NULL AS UPDATEDATE,
    NULL AS UPDATERID
FROM INTRAWARE.APPROVAL AP
WHERE AP.FOLDERID IS NOT NULL
  AND AP.FOLDERID <> '00000000000000000000'
  AND NOT EXISTS (
      SELECT 1 
        FROM INTRAWARE.FLDRMBR2 M 
       WHERE M.FLDRID = AP.FOLDERID 
         AND M.FLDRMBRID = AP.APPRID
  );

COMMIT;

-- 4. 임시 인덱스 삭제 (자원 환원)
DROP INDEX INTRAWARE.IX_TMP_APPR_FOLDER;
DROP INDEX INTRAWARE.IX_TMP_APPRFLDR_MAP;

SELECT '결재문서 편철 매핑 및 FOLDERID 업데이트 완료' AS STATUS, TO_CHAR(SYSDATE, 'YYYY-MM-DD HH24:MI:SS') AS FINISH_TIME FROM DUAL;
