-- 1. 전체 결재문서 대비 편철율 및 미편철 현황 종합 집계
SELECT 
    COUNT(*) AS TOTAL_DOC_COUNT,
    SUM(CASE WHEN FOLDERID IS NOT NULL AND FOLDERID <> '00000000000000000000' THEN 1 ELSE 0 END) AS MAPPED_COUNT,
    SUM(CASE WHEN FOLDERID IS NULL OR FOLDERID = '00000000000000000000' THEN 1 ELSE 0 END) AS UNMAPPED_COUNT,
    ROUND(
        SUM(CASE WHEN FOLDERID IS NOT NULL AND FOLDERID <> '00000000000000000000' THEN 1 ELSE 0 END) / COUNT(*) * 100, 
        2
    ) AS MAPPING_RATE_PCT
FROM INTRAWARE.APPROVAL;


-- 2. 미편철 사유별 유형 분석
SELECT 
    CASE 
        WHEN SAVEDEPTID IS NULL OR SAVEDEPTID = '000000000' THEN '1. 보존부서(SAVEDEPTID) 누락'
        WHEN SPECIALLIST1 IS NULL OR TRIM(SPECIALLIST1) IS NULL THEN '2. 원천 바인드ID(SPECIALLIST1) 누락'
        WHEN NOT EXISTS (SELECT 1 FROM INTRAWARE.APPRFOLDER AF WHERE AF.KEEPINGPERIODCAUSE = A.SPECIALLIST1) THEN '3. 원천 바인드ID에 대응하는 편철함 미존재'
        ELSE '4. 생산년도 또는 부서 매핑 불일치'
    END AS UNMAPPED_REASON,
    COUNT(*) AS CNT
FROM INTRAWARE.APPROVAL A
WHERE A.FOLDERID IS NULL OR A.FOLDERID = '00000000000000000000'
GROUP BY 
    CASE 
        WHEN SAVEDEPTID IS NULL OR SAVEDEPTID = '000000000' THEN '1. 보존부서(SAVEDEPTID) 누락'
        WHEN SPECIALLIST1 IS NULL OR TRIM(SPECIALLIST1) IS NULL THEN '2. 원천 바인드ID(SPECIALLIST1) 누락'
        WHEN NOT EXISTS (SELECT 1 FROM INTRAWARE.APPRFOLDER AF WHERE AF.KEEPINGPERIODCAUSE = A.SPECIALLIST1) THEN '3. 원천 바인드ID에 대응하는 편철함 미존재'
        ELSE '4. 생산년도 또는 부서 매핑 불일치'
    END
ORDER BY CNT DESC;


-- 3. 부서별 미편철 문서 상위 20개 부서
SELECT 
    NVL(DG.DEPT_NAME, '미지정부서') AS DEPT_NAME,
    NVL(DG.DEPT_CODE, A.SAVEDEPTID) AS DEPT_CODE,
    COUNT(*) AS UNMAPPED_COUNT
FROM INTRAWARE.APPROVAL A
LEFT JOIN INTRAWARE.DEPT_GLOBAL DG
  ON A.SAVEDEPTID = DG.DEPT_ID
WHERE A.FOLDERID IS NULL OR A.FOLDERID = '00000000000000000000'
GROUP BY NVL(DG.DEPT_NAME, '미지정부서'), NVL(DG.DEPT_CODE, A.SAVEDEPTID)
ORDER BY UNMAPPED_COUNT DESC;
