-- 
-- * 목적: 편철 매핑 후 FOLDERID가 여전히 NULL이거나 기본값('00000000000000000000')인
--         미편철 결재문서의 건수, 사유, 부서별 분포를 전수 감사하고 구제 방안을 도출합니다.
