-- // 겸직자 정보의 보정 
MERGE /*+ PARALLEL(T, 8) */ INTO INTRAWARE.USR_GLOBAL  T
USING (
	WITH CONC_BASE AS (
	-- 1.겸직자 목록 및 원사번 추출
		SELECT 
			EMP_CODE  AS CONC_EMP_CODE,
			 REGEXP_REPLACE(EMP_CODE,'(_|-)U[0-9]+$','',1,0,'i') AS ORIG_EMP_CODE
		FROM INTRAWARE.USR_GLOBAL 
		WHERE 1=1
		AND REGEXP_LIKE(EMP_CODE,'(_|-)U[0-9]+$','i') 
	),
	ORIG_LIST AS (
	-- 2.겸직을 거느린 원직자 목록 (중복제거)
		SELECT DISTINCT ORIG_EMP_CODE FROM CONC_BASE
	)
	SELECT 
		U.USER_ID ,
		U.EMP_CODE ,
		CASE --1) OTHER_OFFICE_F :겸직자든 원직자든 모두 1
			WHEN C.CONC_EMP_CODE IS NOT NULL OR O.ORIG_EMP_CODE IS NOT NULL THEN '1'
			ELSE '0'
		END AS NEW_OTHER_OFFICE_F, -- 겸직여부
		CASE -- 2) ORG_OTHER_OFFICE_F : 원직자(본인) 에게만 '1' , 겸직자 '0'
			WHEN O.ORIG_EMP_CODE IS NOT NULL AND C.CONC_EMP_CODE IS NULL THEN '1' --원직
			ELSE '0'
		END AS NEW_ORG_OTHER_OFFICE_F , --원직여부
		CASE  --3) USER_COLUMN7  : 겸직자 이면 'Y', 원직자 이면 'N'
			WHEN C.CONC_EMP_CODE IS NOT NULL THEN 'Y' -- 겸직여부
			ELSE 'N'
		END AS NEW_USER_COLUMN7 ,
		CASE -- 4) USER_COLUMN8 원직자 사번 (겸직자 -> 원직자 사번 , 원직자 -> 본인 사번)
			WHEN C.CONC_EMP_CODE IS NOT NULL THEN C.ORIG_EMP_CODE -- 겸직여부
			ELSE U.EMP_CODE
		END AS NEW_USER_COLUMN8	
	FROM INTRAWARE.USR_GLOBAL  U 
	LEFT JOIN CONC_BASE C ON U.EMP_CODE = C.CONC_EMP_CODE
	LEFT JOIN ORIG_LIST O ON U.EMP_CODE = O.ORIG_EMP_CODE
	WHERE
		C.CONC_EMP_CODE IS NOT NULL -- 겸직자 이거나
	OR O.ORIG_EMP_CODE IS NOT NULL  -- 원직자(본인)인 대상만 선별

) S
ON (T.USER_ID = S.USER_ID )
WHEN  MATCHED  THEN 
UPDATE  SET
	T.OTHER_OFFICE_F 		= S.NEW_OTHER_OFFICE_F,
	T.ORG_OTHER_OFFICE_F 	= S.NEW_ORG_OTHER_OFFICE_F,
	T.USER_COLUMN7			= S.NEW_USER_COLUMN7,
	T.USER_COLUMN8			= S.NEW_USER_COLUMN8
	;
	--T.MODIFY_DATE			= SYSDATE
COMMIT;


