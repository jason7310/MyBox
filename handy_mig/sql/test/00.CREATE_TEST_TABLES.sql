-- 목적 : 운영 테이블과 동일한 스키마 구조의 _TEST 테이블을 생성하되,
--        ⭐ 대량 데이터 적재 시 인덱스 갱신 부하(Random I/O)를 원천 차단하기 위해
--           적재 단계에서는 인덱스를 생성하지 않고 순수 테이블만 준비합니다.
--        (인덱스는 데이터 적재 완료 후 '08.CREATE_TEST_INDEXES.sql'에서 병렬 16으로 일괄 고속 생성)
