-- 1. 기존 테스트 테이블이 존재할 경우 안전하게 삭제
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE INTRAWARE.APPROVAL_TEST CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE INTRAWARE.SEND_TEST CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE INTRAWARE.PARTICIPANT_TEST CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE INTRAWARE.FLOW_TEST CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE INTRAWARE.DOCUMENT_TEST CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE INTRAWARE.DOCMBR_TEST CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 2. 운영 테이블 복제 생성 (CTAS WHERE 1=0 : 데이터 및 인덱스 없이 스키마 100% 동일 복제)
CREATE TABLE INTRAWARE.APPROVAL_TEST AS 
SELECT * FROM INTRAWARE.APPROVAL WHERE 1=0;

CREATE TABLE INTRAWARE.SEND_TEST AS 
SELECT * FROM INTRAWARE.SEND WHERE 1=0;

CREATE TABLE INTRAWARE.PARTICIPANT_TEST AS 
SELECT * FROM INTRAWARE.PARTICIPANT WHERE 1=0;

CREATE TABLE INTRAWARE.FLOW_TEST AS 
SELECT * FROM INTRAWARE.FLOW WHERE 1=0;

CREATE TABLE INTRAWARE.DOCUMENT_TEST AS 
SELECT * FROM INTRAWARE.DOCUMENT WHERE 1=0;

CREATE TABLE INTRAWARE.DOCMBR_TEST AS 
SELECT * FROM INTRAWARE.DOCMBR WHERE 1=0;

COMMIT;
