-- 대상 DBMS : Tibero 7 (TAC 2-node 호환)
-- 목적 : _TEST 테이블에 적재된 데이터의 총 건수, 필수값 누락 여부, 퇴직자 매핑 비율,
--        수신문서 첨부파일 중복 절감률을 종합적으로 리포트합니다.
-- ====================================================================================================

-- 1. 테스트 테이블별 총 적재 건수 집계
SELECT 'APPROVAL_TEST' AS TABLE_NAME, COUNT(*) AS TOTAL_CNT FROM INTRAWARE.APPROVAL_TEST
UNION ALL
SELECT 'SEND_TEST', COUNT(*) FROM INTRAWARE.SEND_TEST
UNION ALL
SELECT 'PARTICIPANT_TEST', COUNT(*) FROM INTRAWARE.PARTICIPANT_TEST
UNION ALL
SELECT 'FLOW_TEST', COUNT(*) FROM INTRAWARE.FLOW_TEST
UNION ALL
SELECT 'DOCUMENT_TEST', COUNT(*) FROM INTRAWARE.DOCUMENT_TEST
UNION ALL
SELECT 'DOCMBR_TEST', COUNT(*) FROM INTRAWARE.DOCMBR_TEST;

-- 2. 결재문서(APPROVAL_TEST) 주요 필수 컬럼 NULL 점검 (0건이어야 정상)
SELECT 
    COUNT(CASE WHEN APPRID IS NULL THEN 1 END)             AS NULL_APPRID_CNT,
    COUNT(CASE WHEN TITLE IS NULL THEN 1 END)              AS NULL_TITLE_CNT,
    COUNT(CASE WHEN DRAFTERID IS NULL THEN 1 END)          AS NULL_DRAFTERID_CNT,
    COUNT(CASE WHEN DRAFTERNAME IS NULL THEN 1 END)        AS NULL_DRAFTERNAME_CNT,
    COUNT(CASE WHEN LENGTH(NVL(DOCATTR, '')) <> 80 THEN 1 END) AS INVALID_DOCATTR_LEN_CNT
FROM INTRAWARE.APPROVAL_TEST;

-- 3. 결재선(PARTICIPANT_TEST) 퇴직자 매핑 방어 현황 점검
SELECT 
    COUNT(*)                                               AS TOTAL_PARTICIPANT_CNT,
    COUNT(CASE WHEN SIGNERID <> '000000000' THEN 1 END)    AS NORMAL_USER_MAPPED_CNT,
    COUNT(CASE WHEN SIGNERID = '000000000' THEN 1 END)     AS RETIRED_OR_DEFAULT_CNT,
    COUNT(CASE WHEN SIGNERNAME IS NULL THEN 1 END)         AS NULL_SIGNERNAME_CNT
FROM INTRAWARE.PARTICIPANT_TEST;

-- 4. 첨부파일(DOCUMENT_TEST vs DOCMBR_TEST) 수신문서 중복 제거 효과 검증
SELECT 
    (SELECT COUNT(*) FROM INTRAWARE.DOCMBR_TEST WHERE DOCUMENTTYPE = 100) AS TOTAL_DOCMBR_ATTACH_CNT,
    (SELECT COUNT(*) FROM INTRAWARE.DOCUMENT_TEST WHERE DOCUMENTTYPE = 100) AS PHYSICAL_DOCUMENT_ATTACH_CNT,
    (SELECT COUNT(*) FROM INTRAWARE.DOCMBR_TEST WHERE DOCUMENTTYPE = 100) - 
    (SELECT COUNT(*) FROM INTRAWARE.DOCUMENT_TEST WHERE DOCUMENTTYPE = 100) AS SAVED_DUPLICATE_FILES_CNT
FROM DUAL;
