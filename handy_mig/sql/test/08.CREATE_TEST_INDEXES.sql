-- ====================================================================================================
-- [테스트 환경] 08. 테스트 테이블 인덱스 일괄 병렬 고속 생성 (Bulk Parallel Index Build)
-- 대상 DBMS : Tibero 7 (TAC 2-node 호환)
-- 목적 : 데이터 적재가 완료된 후, 16개 병렬 프로세스를 가동하여 B-Tree 인덱스를
--        메모리 일괄 정렬 방식으로 초고속 구축합니다.
-- ====================================================================================================

ALTER SESSION ENABLE PARALLEL DDL;

-- 1. APPROVAL_TEST 인덱스 병렬 생성
CREATE UNIQUE INDEX INTRAWARE.PK_APPROVAL_TEST 
ON INTRAWARE.APPROVAL_TEST (APPRID) 
PARALLEL 16 NOLOGGING;

CREATE INDEX INTRAWARE.IX_APPROVAL_TEST_DOCID 
ON INTRAWARE.APPROVAL_TEST (DOCID) 
PARALLEL 16 NOLOGGING;

-- 2. SEND_TEST 인덱스 병렬 생성
CREATE UNIQUE INDEX INTRAWARE.PK_SEND_TEST 
ON INTRAWARE.SEND_TEST (SENDID) 
PARALLEL 16 NOLOGGING;

CREATE INDEX INTRAWARE.IX_SEND_TEST_APPRID 
ON INTRAWARE.SEND_TEST (APPRID) 
PARALLEL 16 NOLOGGING;

-- 3. PARTICIPANT_TEST 인덱스 병렬 생성
CREATE UNIQUE INDEX INTRAWARE.PK_PARTICIPANT_TEST 
ON INTRAWARE.PARTICIPANT_TEST (PARTICIPANTID) 
PARALLEL 16 NOLOGGING;

CREATE INDEX INTRAWARE.IX_PARTICIPANT_TEST_APPRID 
ON INTRAWARE.PARTICIPANT_TEST (APPRID, LINETYPE, SEQ) 
PARALLEL 16 NOLOGGING;

-- 4. FLOW_TEST 인덱스 병렬 생성
CREATE UNIQUE INDEX INTRAWARE.PK_FLOW_TEST 
ON INTRAWARE.FLOW_TEST (APPRID, LINETYPE, SEQ) 
PARALLEL 16 NOLOGGING;

-- 5. DOCUMENT_TEST 인덱스 병렬 생성
CREATE UNIQUE INDEX INTRAWARE.PK_DOCUMENT_TEST 
ON INTRAWARE.DOCUMENT_TEST (OBJECTID) 
PARALLEL 16 NOLOGGING;

CREATE INDEX INTRAWARE.IX_DOCUMENT_TEST_SRC 
ON INTRAWARE.DOCUMENT_TEST (SRCOBJECTID) 
PARALLEL 16 NOLOGGING;

-- 6. DOCMBR_TEST 인덱스 병렬 생성
CREATE UNIQUE INDEX INTRAWARE.PK_DOCMBR_TEST 
ON INTRAWARE.DOCMBR_TEST (APPRID, OBJECTID, OBJECTSEQ) 
PARALLEL 16 NOLOGGING;

-- ----------------------------------------------------------------------------------------------------
-- 7. 생성 완료 후 운영 모드로 정상화 (병렬 해제 및 LOGGING 복원)
-- ----------------------------------------------------------------------------------------------------
ALTER INDEX INTRAWARE.PK_APPROVAL_TEST NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.IX_APPROVAL_TEST_DOCID NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.PK_SEND_TEST NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.IX_SEND_TEST_APPRID NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.PK_PARTICIPANT_TEST NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.IX_PARTICIPANT_TEST_APPRID NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.PK_FLOW_TEST NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.PK_DOCUMENT_TEST NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.IX_DOCUMENT_TEST_SRC NOPARALLEL LOGGING;
ALTER INDEX INTRAWARE.PK_DOCMBR_TEST NOPARALLEL LOGGING;

COMMIT;
