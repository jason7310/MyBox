-- 1. INTRAWARE.USR_GLOBAL 실제 컬럼 목록 조회
SELECT 
    COLUMN_ID,
    COLUMN_NAME,
    DATA_TYPE,
    DATA_LENGTH,
    NULLABLE
FROM ALL_TAB_COLS
WHERE OWNER = 'INTRAWARE'
  AND TABLE_NAME = 'USR_GLOBAL'
ORDER BY COLUMN_ID;

