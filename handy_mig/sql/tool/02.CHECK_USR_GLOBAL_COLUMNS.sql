-- 대상 DBMS : Tibero 7 (TAC 2-node)
-- 목적 : INTRAWARE.USR_GLOBAL, DEPT_GLOBAL, POS, RANK 등 실제 테이블 컬럼 목록 및 코멘트 전수 조회
