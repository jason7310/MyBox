-- 6. INTRAWARE 스키마 내 그룹(GROUP) 관련 실제 테이블 목록 전수 조회
SELECT TABLE_NAME 
FROM ALL_TABLES 
WHERE OWNER = 'INTRAWARE' 
  AND (TABLE_NAME LIKE '%GROUP%' OR TABLE_NAME LIKE '%GRP%' OR TABLE_NAME LIKE 'G_%')
ORDER BY TABLE_NAME;
